import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { fetchRosterStandings, buildRoster } from '../scripts/lib/mlb-roster.mjs';
const good = { records: [{ teamRecords: [{ team: { id: 139 }, wins: 90, losses: 72, divisionRank: '2' }] }] };
const options = { season: 2026, date: '2026-10-22', teamId: 139 };
let urls = [];
const fake = async url => {
  urls.push(url);
  if (url.includes('/seasons/')) return { seasons: [{ seasonId: '2026', regularSeasonEndDate: '2026-09-27' }] };
  return url.includes('date=2026-09-27') ? good : { records: [] };
};
assert.deepEqual(await fetchRosterStandings(fake, options), good);
assert.equal(urls.length, 3);
urls = [];
assert.deepEqual(await fetchRosterStandings(fake, { ...options, date: '2026-06-01' }), { records: [] });
assert.equal(urls.length, 2, 'must not use future final standings for an earlier date');
let calls = 0;
assert.deepEqual(await fetchRosterStandings(async () => { calls++; return good; }, options), good);
assert.equal(calls, 1);
assert.deepEqual(await fetchRosterStandings(async () => { throw new Error('HTTP 503'); }, options), { records: [] });
const source = JSON.parse(await fs.readFile(new URL('../runtime/roster-sources.json', import.meta.url))).teams['139'];
const inputs = { source, active: { roster: [] }, fortyMan: { roster: [] }, coaches: { roster: [] }, team: { teams: [{ id: 139, division: { id: 201 } }] }, fetchedAt: '2026-10-23T00:00:00Z' };
const missing = buildRoster({ ...inputs, standings: { records: [] } });
assert.equal(missing.record, null);
assert.equal(missing.players.length, source.players.length);
assert.equal(missing.teamName, source.teamName);
assert.ok(missing.manager.displayName);
const normal = buildRoster({ ...inputs, standings: good });
assert.equal(normal.record.wins, 90);
assert.equal(normal.record.divisionRank, 2);
console.log('PASS roster standings: postseason fallback, historical dates, API failure, roster preserved');
